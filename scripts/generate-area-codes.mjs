// Builds src/lib/phone/area-code-data.ts from Google's libphonenumber data
// (via the libphonenumber-geo-carrier package). To refresh:
//   npm i --no-save --legacy-peer-deps libphonenumber-geo-carrier
//   node scripts/generate-area-codes.mjs
import fs from "node:fs";
import { createRequire } from "node:module";

const require = createRequire(import.meta.url);
const { BSON } = require("bson");
const root = "node_modules/libphonenumber-geo-carrier/resources";
const tz = BSON.deserialize(fs.readFileSync(`${root}/timezones.bson`));
const geo = BSON.deserialize(fs.readFileSync(`${root}/geocodes/en/1.bson`));

const STATES = {
  Alabama: "AL", Alaska: "AK", Arizona: "AZ", Arkansas: "AR", California: "CA", Colorado: "CO",
  Connecticut: "CT", Delaware: "DE", "Washington D.C.": "DC", Florida: "FL", Georgia: "GA", Hawaii: "HI",
  Idaho: "ID", Illinois: "IL", Indiana: "IN", Iowa: "IA", Kansas: "KS", Kentucky: "KY", Louisiana: "LA",
  Maine: "ME", Maryland: "MD", Massachusetts: "MA", Michigan: "MI", Minnesota: "MN", Mississippi: "MS",
  Missouri: "MO", Montana: "MT", Nebraska: "NE", Nevada: "NV", "New Hampshire": "NH", "New Jersey": "NJ",
  "New Mexico": "NM", "New York": "NY", "North Carolina": "NC", "North Dakota": "ND", Ohio: "OH",
  Oklahoma: "OK", Oregon: "OR", Pennsylvania: "PA", "Rhode Island": "RI", "South Carolina": "SC",
  "South Dakota": "SD", Tennessee: "TN", Texas: "TX", Utah: "UT", Vermont: "VT", Virginia: "VA",
  "Washington State": "WA", "West Virginia": "WV", Wisconsin: "WI", Wyoming: "WY",
};
const US_CODES = new Set(Object.values(STATES));

function stateOf(label) {
  if (STATES[label]) return STATES[label];
  const m = label.match(/, ([A-Z]{2})$/); // e.g. "Chicago, IL"
  return m && US_CODES.has(m[1]) ? m[1] : null;
}

function majority(values) {
  const counts = new Map();
  for (const v of values) if (v) counts.set(v, (counts.get(v) ?? 0) + 1);
  return [...counts.entries()].sort((a, b) => b[1] - a[1])[0]?.[0] ?? null;
}

// Some area codes only have data at a finer level (e.g. 208, 310), so fall
// back to the most common state / zone among their longer prefixes.
const candidates = new Set(Object.keys(geo).filter((k) => k.length >= 3).map((k) => k.slice(0, 3)));
const areaCodes = {}; // "954" -> ["FL", "America/New_York"]
for (const ac of candidates) {
  const state =
    (geo[ac] && stateOf(geo[ac])) ||
    majority(Object.entries(geo).filter(([k]) => k.startsWith(ac)).map(([, v]) => stateOf(v)));
  const zone =
    tz[`1${ac}`]?.split("&")[0] ||
    majority(Object.entries(tz).filter(([k]) => k.startsWith(`1${ac}`)).map(([, v]) => v.split("&")[0]));
  if (state && zone) areaCodes[ac] = [state, zone];
}

// Finer prefixes (area code + exchange digits) where the time zone differs
// from the area code's default, e.g. Pensacola numbers inside 850.
const prefixes = {};
for (const [key, zones] of Object.entries(tz)) {
  if (!key.startsWith("1") || key.length <= 4) continue;
  const digits = key.slice(1);
  const base = areaCodes[digits.slice(0, 3)];
  if (!base) continue;
  const zone = zones.split("&")[0];
  if (zone !== base[1]) prefixes[digits] = zone;
}

const sort = (o) => Object.fromEntries(Object.entries(o).sort(([a], [b]) => a.localeCompare(b)));
const out = `// GENERATED by scripts/generate-area-codes.mjs from Google libphonenumber data. Do not edit by hand.
// US area codes only.

/** Area code -> [state, IANA time zone] */
export const AREA_CODES: Record<string, [string, string]> = ${JSON.stringify(sort(areaCodes))};

/** Longer number prefixes whose time zone differs from their area code's default. */
export const TZ_PREFIXES: Record<string, string> = ${JSON.stringify(sort(prefixes))};
`;
fs.writeFileSync("src/lib/phone/area-code-data.ts", out);
console.log(`area codes: ${Object.keys(areaCodes).length}, override prefixes: ${Object.keys(prefixes).length}`);
